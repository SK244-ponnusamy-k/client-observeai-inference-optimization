"""
GPU (NVIDIA vLLM DLC) template set.

Each template reproduces the platform's reviewed, hardened file. Per-model values
are {{placeholders}}; deploy-time envsubst variables (${MODEL_BUCKET}, etc.) are
left intact for the generated deploy.sh to resolve. Security hardening
(non-root, readOnlyRootFilesystem, drop ALL caps, seccomp, pinned image via
config.env, ClusterIP-only service, least-privilege serving SA) is baked in and
never exposed as a knob, so a generated model cannot accidentally weaken it.
"""

