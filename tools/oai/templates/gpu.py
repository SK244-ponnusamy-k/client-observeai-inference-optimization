DEPLOY_SH = """\
#!/bin/bash
# ==============================================================================
# vllm/models/{{id}}/deploy.sh  - GENERATED by `oai model generate {{id}}`
#
# Generic deploy - model-specific names come from model.env.
# Usually you run this via the friendly wrapper:  oai deploy {{id}}
# but it also works standalone.
#
# Usage:
#   bash vllm/models/{{id}}/deploy.sh                  # defaults (model.env)
#   bash vllm/models/{{id}}/deploy.sh --hw g5.2xlarge  # pin GPU family/size
#   bash vllm/models/{{id}}/deploy.sh --validate       # smoke-test after ready
# ==============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FRAMEWORK_ROOT="$(cd "${SCRIPT_DIR}/../../.." && pwd)"
source "${FRAMEWORK_ROOT}/config/config.env"
source "${SCRIPT_DIR}/model.env"

: "${VLLM_IMAGE:?ERROR: VLLM_IMAGE is not set. Ensure config/config.env exports it with a pinned digest.}"

GREEN='\\033[0;32m'; YELLOW='\\033[1;33m'; RED='\\033[0;31m'; NC='\\033[0m'
log_info()  { echo -e "${GREEN}[INFO]  $(date +'%H:%M:%S')${NC} $1"; }
log_warn()  { echo -e "${YELLOW}[WARN]  $(date +'%H:%M:%S')${NC} $1"; }
log_error() { echo -e "${RED}[ERROR] $(date +'%H:%M:%S')${NC} $1"; }

VALIDATE="false"
while [[ $# -gt 0 ]]; do
    case "$1" in
        --hw)       NODE_INSTANCE_TYPE="$2"; shift 2 ;;
        --tp)       TP_SIZE="$2"; shift 2 ;;
        --validate) VALIDATE="true"; shift ;;
        *) log_warn "Unknown arg: $1"; shift ;;
    esac
done
GPU_COUNT="${TP_SIZE}"
export NODE_INSTANCE_TYPE TP_SIZE GPU_COUNT MODEL_FOLDER SERVED_NAME

echo ""
echo "=================================================="
echo "  DEPLOYING - {{hf_id}}"
echo "  Deployment    : ${DEPLOYMENT_NAME}"
echo "  Service       : ${SERVICE_NAME}:8000"
echo "  Namespace     : ${BENCHMARK_NAMESPACE}"
echo "  Instance type : ${NODE_INSTANCE_TYPE}   (TP=${TP_SIZE}, GPUs=${GPU_COUNT})"
echo "=================================================="
echo ""

log_info "Checking model in S3..."
if ! aws s3 ls "s3://${MODEL_BUCKET}/${MODEL_FOLDER}/" --region "${AWS_REGION}" >/dev/null 2>&1; then
    log_error "Model not found: s3://${MODEL_BUCKET}/${MODEL_FOLDER}/"
    log_error "Download it first: oai download {{id}}   (or bash model-download/{{id}}/download.sh)"
    exit 1
fi
log_info "Model found in S3."

log_info "Applying PVC..."
kubectl apply -f "${SCRIPT_DIR}/pvc.yaml"

log_info "Applying service: ${SERVICE_NAME}..."
kubectl apply -f "${SCRIPT_DIR}/service.yaml"

log_info "Applying deployment: ${DEPLOYMENT_NAME} on ${NODE_INSTANCE_TYPE}..."
export MODEL_BUCKET BENCHMARK_NAMESPACE VLLM_IMAGE
envsubst '${MODEL_BUCKET} ${BENCHMARK_NAMESPACE} ${VLLM_IMAGE} ${MODEL_FOLDER} ${SERVED_NAME} ${NODE_INSTANCE_TYPE} ${TP_SIZE} ${GPU_COUNT}' \\
    < "${SCRIPT_DIR}/deployment.yaml" | kubectl apply -f -

log_info "Waiting for pod (Karpenter provisioning ${NODE_INSTANCE_TYPE} ~2-4 min)..."
sleep 10
for i in $(seq 1 24); do
    POD=$(kubectl get pods -l app="${DEPLOYMENT_NAME}" -n "${BENCHMARK_NAMESPACE}" \\
        -o jsonpath='{.items[0].metadata.name}' 2>/dev/null || true)
    [[ -n "${POD}" ]] && break
    echo -n "."
    sleep 5
done
echo ""
log_info "Pod: ${POD:-not found yet}"

log_info "Waiting for Ready (model loading from S3 - up to 10 min)..."
kubectl wait "deployment/${DEPLOYMENT_NAME}" \\
    --for=condition=Available --timeout=600s -n "${BENCHMARK_NAMESPACE}" || {
    log_warn "Deployment not ready yet - check logs:"
    log_warn "  kubectl logs deployment/${DEPLOYMENT_NAME} -n ${BENCHMARK_NAMESPACE} | tail -30"
}

echo ""
echo "=================================================="
echo "  DEPLOYED - {{id}} on ${NODE_INSTANCE_TYPE}"
echo "=================================================="
kubectl get pods -l app="${DEPLOYMENT_NAME}" -n "${BENCHMARK_NAMESPACE}" -o wide
echo ""
echo "  Port-forward:"
echo "    kubectl port-forward svc/${SERVICE_NAME} ${PORT_FORWARD_PORT}:8000 -n ${BENCHMARK_NAMESPACE} &"
echo "    curl http://localhost:${PORT_FORWARD_PORT}/health"
echo "=================================================="

if [[ "${VALIDATE}" == "true" ]]; then
    echo ""
    log_info "Starting post-deploy validation (--validate flag set)..."
    bash "${SCRIPT_DIR}/../post-deploy-validate.sh" \\
        --model "${MODEL_ID}" \\
        --manifest "${MANIFEST_PATH}" \\
        --endpoint "http://${SERVICE_NAME}:8000"
fi
"""

STOP_SH = """\
#!/bin/bash
# ==============================================================================
# vllm/models/{{id}}/stop.sh  - GENERATED by `oai model generate {{id}}`
#
# Full teardown for {{id}}. Deletes the deployment/service/PVC and terminates
# THIS model's GPU node so billing stops. Leaves S3 weights and monitoring alone.
#
# Friendly wrapper:  oai stop {{id}}
# ==============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FRAMEWORK_ROOT="$(cd "${SCRIPT_DIR}/../../.." && pwd)"
source "${FRAMEWORK_ROOT}/config/config.env"
source "${SCRIPT_DIR}/model.env"
source "${FRAMEWORK_ROOT}/vllm/lib/gpu-terminate.sh"

GREEN='\\033[0;32m'; YELLOW='\\033[1;33m'; NC='\\033[0m'
log_info()  { echo -e "${GREEN}[INFO]  $(date +'%H:%M:%S')${NC} $1"; }
log_warn()  { echo -e "${YELLOW}[WARN]  $(date +'%H:%M:%S')${NC} $1"; }

echo ""
echo "=================================================="
echo "  FULL STOP - ${MODEL_ID}"
echo "  Deployment : ${DEPLOYMENT_NAME}"
echo "  Namespace  : ${BENCHMARK_NAMESPACE}"
echo "=================================================="
echo ""
echo "  This will:"
echo "    - Delete vLLM deployment, service, PVC"
echo "    - Terminate GPU node for this model (stops billing)"
echo "    - Clean up benchmark jobs for this model only"
echo "    - Leave monitoring stack running"
echo ""

if [[ "${OAI_ASSUME_YES:-false}" != "true" ]]; then
    read -r -p "Proceed? [y/N]: " CONFIRM
    [[ "${CONFIRM}" =~ ^[yY]$ ]] || { log_info "Cancelled."; exit 0; }
fi

log_info "Looking up node for deployment: ${DEPLOYMENT_NAME}..."
MODEL_NODE=$(kubectl get pod -l "app=${DEPLOYMENT_NAME}" -n "${BENCHMARK_NAMESPACE}" \\
    -o jsonpath='{.items[0].spec.nodeName}' 2>/dev/null || true)
[[ -n "${MODEL_NODE}" ]] && log_info "Model is running on node: ${MODEL_NODE}" || \\
    log_warn "Pod not found - node will be located via nodeclaim instance type."

log_info "Deleting deployment: ${DEPLOYMENT_NAME}..."
kubectl delete deployment "${DEPLOYMENT_NAME}" -n "${BENCHMARK_NAMESPACE}" --ignore-not-found=true
log_info "Deleting service: ${SERVICE_NAME}..."
kubectl delete svc "${SERVICE_NAME}" -n "${BENCHMARK_NAMESPACE}" --ignore-not-found=true
log_info "Deleting PVC: ${PVC_NAME}..."
kubectl delete pvc "${PVC_NAME}" -n "${BENCHMARK_NAMESPACE}" --ignore-not-found=true 2>/dev/null || true

terminate_model_gpu_node "${DEPLOYMENT_NAME}" "${BENCHMARK_NAMESPACE}" "${MODEL_NODE:-}"

log_info "Cleaning up benchmark jobs for model '${MODEL_ID}'..."
kubectl delete jobs -n "${BENCHMARK_NAMESPACE}" \\
    -l "app.kubernetes.io/component=benchmark-runner,model=${MODEL_ID}" \\
    --ignore-not-found=true 2>/dev/null || true

print_stop_summary "${MODEL_ID}" "${BENCHMARK_NAMESPACE}"
"""
