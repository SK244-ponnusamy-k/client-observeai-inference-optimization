JOB_YAML = """\
# ==============================================================================
# model-download/{{id}}/job.yaml  - GENERATED by `oai model generate {{id}}`
#
# Kubernetes Job: downloads {{hf_id}} from HuggingFace -> S3.
# Runtime values injected via envsubst by download.sh:
#   ${MODEL_BUCKET} ${AWS_REGION} ${DOWNLOAD_SERVICE_ACCOUNT} ${BENCHMARK_NAMESPACE}
#
# Security hardening: non-root (nobody UID 65534), readOnlyRootFilesystem,
# drop ALL caps, no priv-esc, automountServiceAccountToken false, seccomp
# RuntimeDefault, CPU+mem requests/limits.{{token_security_note}}
# ==============================================================================

apiVersion: batch/v1
kind: Job
metadata:
  name: {{download_job_name}}
  namespace: ${BENCHMARK_NAMESPACE}
  labels:
    app.kubernetes.io/name: {{download_job_name}}
    app.kubernetes.io/component: model-download
    app.kubernetes.io/managed-by: oai-cli
    project: observeai-inference-optimization
    engagement: shellkode-sow
    environment: sandbox
    model: {{id}}
spec:
  backoffLimit: 2
  activeDeadlineSeconds: 86400
  ttlSecondsAfterFinished: 3600
  template:
    metadata:
      labels:
        app.kubernetes.io/name: {{download_job_name}}
        app.kubernetes.io/component: model-download
        project: observeai-inference-optimization
        engagement: shellkode-sow
        environment: sandbox
        model: {{id}}
    spec:
      restartPolicy: Never
      serviceAccountName: ${DOWNLOAD_SERVICE_ACCOUNT}
      automountServiceAccountToken: false
      hostPID: false
      hostIPC: false
      hostNetwork: false
      securityContext:
        runAsNonRoot: true
        runAsUser: 65534
        runAsGroup: 65534
        fsGroup: 65534
        seccompProfile:
          type: RuntimeDefault
      containers:
        - name: downloader
          image: python:3.11-slim@sha256:d1053354624536b044162aaab1e418bd000ea35184fb1ae098ab3166b1072e72
          imagePullPolicy: IfNotPresent
          command: ["/bin/bash", "-c"]
          args:
            - |
              set -euo pipefail
              MODEL_ID="{{hf_id}}"
              MODEL_FOLDER="{{download_folder}}"
              LOCAL_DIR="/tmp/${MODEL_FOLDER}"

              echo "Model  : ${MODEL_ID}"
              echo "Bucket : s3://${MODEL_BUCKET}/${MODEL_FOLDER}/"

              echo "Installing dependencies..."
              pip install --quiet --no-cache-dir --target /tmp/pip-packages \\
                  huggingface_hub==0.24.7 boto3==1.34.0
              export PYTHONPATH="/tmp/pip-packages:${PYTHONPATH:-}"

              echo "Downloading from HuggingFace..."
              python3 -c "
              import os
              from huggingface_hub import snapshot_download
              token = None
              {{token_python_block}}
              snapshot_download(
                  repo_id='${MODEL_ID}',
                  local_dir='${LOCAL_DIR}',
                  token=token,
                  ignore_patterns={{ignore_patterns}},
              )
              print('HF download complete.')
              "

              echo "Files downloaded:"; ls -lah "${LOCAL_DIR}/"

              echo "Uploading to s3://${MODEL_BUCKET}/${MODEL_FOLDER}/ ..."
              MODEL_FOLDER="${MODEL_FOLDER}" python3 << 'PYEOF'
              import boto3, os
              from pathlib import Path
              s3 = boto3.client("s3", region_name=os.environ["AWS_DEFAULT_REGION"])
              bucket = os.environ["MODEL_BUCKET"]
              folder = os.environ["MODEL_FOLDER"]
              local_dir = Path(f"/tmp/{folder}")
              files = [f for f in local_dir.rglob("*") if f.is_file() and ".cache" not in f.parts]
              print(f"Uploading {len(files)} files...")
              for i, f in enumerate(files, 1):
                  key = f"{folder}/" + str(f.relative_to(local_dir))
                  print(f"[{i}/{len(files)}] {f.name} ({f.stat().st_size/1_048_576:.1f} MB)")
                  s3.upload_file(str(f), bucket, key)
              print("Upload complete.")
              PYEOF
          env:
            - name: AWS_DEFAULT_REGION
              value: "${AWS_REGION}"
            - name: MODEL_BUCKET
              value: "${MODEL_BUCKET}"
            - name: HF_HUB_DISABLE_TELEMETRY
              value: "1"
            - name: TRANSFORMERS_CACHE
              value: "/tmp/hf-cache"
            - name: HF_HOME
              value: "/tmp/hf-home"
            - name: PIP_NO_CACHE_DIR
              value: "1"
          securityContext:
            allowPrivilegeEscalation: false
            readOnlyRootFilesystem: true
            runAsNonRoot: true
            runAsUser: 65534
            runAsGroup: 65534
            capabilities:
              drop: ["ALL"]
            seccompProfile:
              type: RuntimeDefault
          resources:
            requests:
              cpu: "4"
              memory: "16Gi"
            limits:
              cpu: "8"
              memory: "32Gi"
          volumeMounts:
            - name: tmp-workspace
              mountPath: /tmp
{{token_volume_mount}}
      volumes:
        - name: tmp-workspace
          emptyDir:
            sizeLimit: {{download_scratch_gi}}Gi
{{token_volume}}
"""

